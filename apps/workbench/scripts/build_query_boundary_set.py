def main() -> None:
    DEST.mkdir(parents=True, exist_ok=True)
    taxonomy_path = (
        ROOT / "data/processed/knowledge/finrisk_full_20261024/dictionary/risk_type_dictionary.csv"
    )
    with taxonomy_path.open(encoding="utf-8-sig") as stream:
        taxonomy = {r["risk_tag"] for r in csv.DictReader(stream)}
    scenes = {
        1: "ST1_poster_sms_social",
        2: "ST2_live_short_video",
        3: "ST3_product_intro_detail",
        4: "ST4_meeting_material",
        5: "ST5_training_telemarketing_callback",
        6: "ST6_penalty_backend_fact",
    }
    counts = {}
    for split, groups in (("train", TRAIN), ("validation", VALIDATION)):
        rows = []
        for index, (group, scene, risk, labels, normal, unknown, gaps) in enumerate(groups, 1):
            for variant, state, text, confirmed, missing in [
                ("risk", "risk", risk, labels, []),
                ("normal", "no_clear_risk", normal, [], []),
                ("unknown", "insufficient_information", unknown, [], gaps),
            ]:
                if split == "validation" and group == "long_document_independent_fact":
                    filler = (
                        "培训日程登记只用于安排会议，不对保险收益、客户身份和业务事实作任何承诺。\n"
                        * 44
                    )
                    text = text.replace("\n\n", "\n\n" + filler + "\n\n", 1)
                assert set(labels) <= taxonomy
                row = {
                    "query_id": f"QB24-{split.upper()}-{index:02d}-{variant}",
                    "group_id": group,
                    "split": split,
                    "text": text,
                    "scene": scenes[scene],
                    "decision_state": state,
                    "risk_labels": confirmed,
                    "candidate_labels": labels if state == "insufficient_information" else [],
                    "missing_facts": missing,
                    "source_text_sha256": hashlib.sha256(text.encode()).hexdigest(),
                    "annotation_origin": "codex_authored_synthetic_boundary_set",
                    "human_expert_gold": False,
                    "external_annotation_model_calls": 0,
                    "evidence": [
                        {
                            "quote": text,
                            "start": 0,
                            "end": len(text),
                            "offset_unit": "unicode_codepoint",
                        }
                    ],
                    "annotation_basis": (
                        "当前输入明确记载已作出的主张或实施事实；逐标签按定义独立核对"
                    )
                    if state == "risk"
                    else (
                        "当前输入仅有合规流程、明确否定或未采纳示例，"
                        "不将风险词或其他业务当作实施事实"
                    )
                    if state == "no_clear_risk"
                    else "实际主张依赖具体未明条件，待核不升级为已成立风险：" + "、".join(missing),
                }
                rows.append(row)
        (DEST / f"{split}.jsonl").write_text(
            "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
        )
        counts[split] = {
            "queries": len(rows),
            "groups": len(groups),
            "states": dict(Counter(r["decision_state"] for r in rows)),
            "labels": dict(Counter(t for r in rows for t in r["risk_labels"])),
            "long_queries": sum(len(r["text"]) >= 1600 for r in rows),
        }
    assert len(counts["train"]["labels"]) == 27
    manifest = {
        "version": "query-boundaries-20261024-v1",
        "author": "Codex direct authoring and review",
        "purpose": (
            "local candidate training and few-shot calibration; no DeepSeek weight fine-tuning"
        ),
        "splits_by": "scenario_group; validation groups do not appear in training",
        "counts": counts,
        "test_queries_used_for_authoring": 0,
        "test_reference_modified": False,
        "taxonomy_sha256": hashlib.sha256(taxonomy_path.read_bytes()).hexdigest(),
        "files": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in DEST.glob("*.jsonl")},
    }
    (DEST / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
